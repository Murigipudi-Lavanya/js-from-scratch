let a = 10; // Numeric literal assigned to the variable 'a'.
console.log(a); // Output: 10

let b = 3.14; // Floating-point literal assigned to the variable 'b'.
console.log(b); // Output: 3.14

let c = 0b1010; // Binary literal assigned to the variable 'c'.
console.log(c); // Output: 10

let d = 0o12; // Octal literal assigned to the variable 'd'.
console.log(d); // Output: 10

let e = 0xA; // Hexadecimal literal assigned to the variable 'e'.
console.log(e); // Output: 10   

console.log("Datatype of b is:" + typeof(b) );
console.log("Datatype of c is:" + typeof(c) );
console.log("Datatype of d is:" + typeof(d) );
console.log("Datatype of e is:" + typeof(e) );

// Exponential notation
let exp1 = 1.5e3;   // 1.5 * 10^3 = 1500
let exp2 = 1.5e-3;  // 1.5 * 10^-3 = 0.0015
let exp3 = 2E10;    // 2 * 10^10 = 20000000000

console.log("Exponential 1.5e3:", exp1);   // 1500
console.log("Exponential 1.5e-3:", exp2);  // 0.0015
console.log("Exponential 2E10:", exp3);    // 20000000000