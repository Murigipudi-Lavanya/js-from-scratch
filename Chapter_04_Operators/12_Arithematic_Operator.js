let a =10;
let b= 20;

//  Adding two numbers using the arithmetic + operator
let sum = a + b;
console.log(sum);

// Subtracting two numbers using the arithmetic - operator
let difference = a - b;
console.log(difference);

// Multiplying two numbers using the arithmetic * operator
let product = a * b;
console.log(product);

// Dividing two numbers using the arithmetic / operator
let quotient = a / b;
console.log(quotient);

// Modulus of two numbers using the arithmetic % operator
let remainder = a % b;
console.log(remainder);

// Incrementing a number using the arithmetic ++ operator
a++;
console.log(a);

// Decrementing a number using the arithmetic -- operator
b--;
console.log(b); 
